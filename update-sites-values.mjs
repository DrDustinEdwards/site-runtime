#!/usr/bin/env node
/**
 * Writes the registry (sites.mjs, where entries are written with their reasons) as the two files the package serves,
 * so a Worker bundles each value once and none of the prose it never reads:
 *
 * - sites-values.mjs: every entry's values, with no `reason` and no `deviations` (`./sites`, what a Worker imports),
 *   and siteEntry, siteForOrigin, siteOverrides and SITES over them.
 * - sites-deviations.mjs: each entry's deviations by id, and FAMILY_DEVIATIONS: the only reasons anything prints, which
 *   only the check (and the bins through it) imports and joins to the values (check.mjs registryEntry).
 *
 * The other reasons (each header override's and opt-in's) are for the people who read sites.mjs; the registry test
 * holds that each is written.
 *
 *   node update-sites-values.mjs
 *
 * Run it after every change to sites.mjs; test/sites.test.mjs fails while they disagree.
 */

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { permissionsAllowingSelf } from "./headers.mjs";
import * as registry from "./sites.mjs";

/** Code written as it is, not as a value: a header value the package's own helper computes, kept as that call. */
class Code {
  /** @param {string} code */
  constructor(code) {
    this.code = code;
  }
  toJSON() {
    return `\u0000${this.code}`;
  }
}

/** A Permissions-Policy value as the permissionsAllowingSelf call that writes it, or the value when no call does. @param {string} value */
function permissionsCode(value) {
  const standard = permissionsAllowingSelf();
  const features = value.split(", ").filter((d) => d.endsWith("=(self)") && !standard.split(", ").includes(d)).map((d) => d.slice(0, -"=(self)".length));
  return permissionsAllowingSelf(...features) === value ? new Code(`permissionsAllowingSelf(${features.map((f) => JSON.stringify(f)).join(", ")})`) : value;
}

const HEADER = "// GENERATED by update-sites-values.mjs from sites.mjs. Do not edit: change sites.mjs and run `node update-sites-values.mjs`.";

/** @param {unknown} value @param {string} [name] */
function values(value, name) {
  if (Array.isArray(value)) return value.map((v) => values(v));
  if (value === null || typeof value !== "object") return name === "Permissions-Policy" && typeof value === "string" ? permissionsCode(value) : value;
  return Object.fromEntries(Object.entries(value).filter(([k]) => k !== "reason" && k !== "deviations").map(([k, v]) => [k, values(v, k === "value" ? name : k)]));
}

/**
 * JavaScript for `roots` (name to value), with every long string, object or array that appears more than once written
 * once as a const, so a bundle holds each shared reason, header value or opt-in once, as sites.mjs does.
 * @param {[string, unknown][]} roots
 */
function deduped(roots) {
  /** @type {Map<string, number>} */
  const counts = new Map();
  const key = (/** @type {unknown} */ v) => JSON.stringify(v);
  const count = (/** @type {unknown} */ v) => {
    if (v instanceof Code) return;
    if (typeof v === "string" || (v && typeof v === "object")) counts.set(key(v), (counts.get(key(v)) ?? 0) + 1);
    if (v && typeof v === "object") for (const x of Object.values(v)) count(x);
  };
  for (const [, v] of roots) for (const x of Object.values(/** @type {object} */ (v))) count(x);
  /** @type {Map<string, string>} */
  const ids = new Map();
  /** @type {string[]} */
  const consts = [];
  /** @returns {string} */
  const js = (/** @type {unknown} */ v) => {
    if (v instanceof Code) return `/* @__PURE__ */ ${v.code}`;
    const k = key(v);
    if (ids.has(k)) return /** @type {string} */ (ids.get(k));
    let text;
    if (Array.isArray(v)) text = `[${v.map(js).join(",")}]`;
    else if (v && typeof v === "object") text = `{${Object.entries(v).map(([name, x]) => `${JSON.stringify(name)}:${js(x)}`).join(",")}}`;
    else return k;
    if ((counts.get(k) ?? 0) > 1 && k.length >= 20) {
      const id = `s${ids.size}`;
      ids.set(k, id);
      consts.push(`const ${id} = ${text};`);
      return id;
    }
    return text;
  };
  const strings = (/** @type {unknown} */ v) => {
    if (typeof v === "string") {
      const k = key(v);
      if (!ids.has(k) && (counts.get(k) ?? 0) > 1 && k.length >= 24) {
        ids.set(k, `s${ids.size}`);
        consts.push(`const ${ids.get(k)} = ${k};`);
      }
    } else if (v && typeof v === "object") for (const x of Object.values(v)) strings(x);
  };
  for (const [, v] of roots) strings(v);
  return { consts, js };
}

const names = () => Object.keys(registry).filter((n) => typeof registry[n] === "object" && registry[n] !== null && typeof registry[n].id === "string");

function valuesBody() {
  const roots = names().map((n) => /** @type {[string, unknown]} */ ([n, values(registry[n])]));
  const { consts, js } = deduped(roots);
  const exported = roots.map(([n, v]) => `export const ${n} = ${js(v)};`);
  return [...consts, "", ...exported];
}

/** sites-values.mjs as it should read now. */
export function sitesValuesSource() {
  return [
    HEADER,
    "// The registry's values, the file a Worker bundles (package.json exports, ./sites); the reasons are sites-reasons.mjs.",
    "",
    'import { entryOverrides, permissionsAllowingSelf } from "./headers.mjs";',
    'export { PASSKEY_OVERRIDES, permissionsAllowingSelf } from "./headers.mjs";',
    "",
    ...valuesBody(),
    "",
    `export const SITES = /* @__PURE__ */ Object.freeze([${registry.SITES.map((s) => names().find((n) => registry[n] === s)).join(", ")}]);`,
    "",
    "/** The entry for an id; unknown ids throw. @param {string} id */",
    "export function siteEntry(id) {",
    "  const entry = SITES.find((s) => s.id === id);",
    "  if (!entry) throw new Error(`${JSON.stringify(id)} is not in the site registry (sites.mjs)`);",
    "  return entry;",
    "}",
    "",
    "/** The entry whose origin or alias is `origin`, or undefined. @param {string} origin */",
    "export function siteForOrigin(origin) {",
    "  const bare = new URL(origin).origin;",
    "  return SITES.find((s) => s.origin === bare || (s.aliases ?? []).includes(bare));",
    "}",
    "",
    "/** The header overrides an entry declares (entryOverrides, ./headers), by id. @param {string} id */",
    "export function siteOverrides(id) {",
    "  return entryOverrides(siteEntry(id));",
    "}",
    "",
  ].join("\n");
}

/** sites-deviations.mjs as it should read now. */
export function sitesDeviationsSource() {
  const byId = Object.fromEntries(registry.SITES.flatMap((s) => (s.deviations ? [[s.id, s.deviations]] : [])));
  const { consts, js } = deduped([["SITE_DEVIATIONS", byId]]);
  const body = `export const SITE_DEVIATIONS = /* @__PURE__ */ Object.freeze(${js(byId)});`;
  return [
    HEADER,
    "// The registry's deviations by site id and the family's, which only the check reads (check.mjs joins them to sites-values.mjs).",
    "",
    `export const FAMILY_DEVIATIONS = /* @__PURE__ */ Object.freeze(${JSON.stringify(registry.FAMILY_DEVIATIONS)});`,
    "",
    ...consts,
    "",
    body,
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL("./sites-values.mjs", import.meta.url), sitesValuesSource());
  writeFileSync(new URL("./sites-deviations.mjs", import.meta.url), sitesDeviationsSource());
}
